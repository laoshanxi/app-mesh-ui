#!/bin/sh

# Generate config.js from template
envsubst </usr/share/nginx/html/config.js.template >/usr/share/nginx/html/config.js

# Optional upstream TLS verification: PROXY_SSL_VERIFY=on rejects a
# self-signed / MITM-ed API upstream, but nginx then needs the CA that signed
# it. APP_MESH_API_CA is a file path mounted into the container; when set, an
# http-level snippet wires it in (proxy_ssl_* directives are inherited by the
# proxy locations in default.conf).
if [ "${PROXY_SSL_VERIFY:-off}" = "on" ] && [ -z "${APP_MESH_API_CA:-}" ]; then
	echo "appmesh-ui: PROXY_SSL_VERIFY=on needs APP_MESH_API_CA (a mounted CA bundle), exiting" >&2
	exit 1
fi
if [ -n "${APP_MESH_API_CA:-}" ]; then
	if [ -f "$APP_MESH_API_CA" ]; then
		cat >/etc/nginx/conf.d/00-upstream-ca.conf <<EOF
# Generated by 99-custom-config.sh from APP_MESH_API_CA
proxy_ssl_trusted_certificate $APP_MESH_API_CA;
proxy_ssl_verify_depth 2;
EOF
		echo "appmesh-ui: API upstream verification against $APP_MESH_API_CA"
	else
		echo "appmesh-ui: APP_MESH_API_CA=$APP_MESH_API_CA not found, exiting" >&2
		exit 1
	fi
fi

# Whitelist for the 497 plain-HTTP bounce (error_page 497 in default.conf):
# only a Host the deployment answers on is echoed back with its port, every
# other Host falls back to $host. The UI_PUBLIC_HOST line is emitted only when
# the variable is non-empty — an empty value would otherwise render the regex
# ~^(:[0-9]+)?$ (matches a missing Host) and degrade the bounce to
# "https:///path". The value is a regex fragment: regex metacharacters must be
# escaped by the deployer (e.g. ui\.example\.com) or a lookalike host matches
# too. The map lives at http level in its own conf.d fragment.
public_host_line=''
if [ -n "${UI_PUBLIC_HOST:-}" ]; then
	public_host_line="    ~*^${UI_PUBLIC_HOST}(:[0-9]+)?\$      \$http_host;"
	echo "appmesh-ui: 497 bounce whitelist includes UI_PUBLIC_HOST=${UI_PUBLIC_HOST}"
fi
cat >/etc/nginx/conf.d/00-bounce-host.conf <<EOF
# Generated by 99-custom-config.sh: hosts whose Host header the 497
# plain-HTTP-to-TLS-port bounce may echo back with its port
map \$http_host \$bounce_host {
    default                        \$host;
    ~*^localhost(:[0-9]+)?\$        \$http_host;
    ~*^127\.0\.0\.1(:[0-9]+)?\$     \$http_host;
    ~*^\[::1\](:[0-9]+)?\$          \$http_host;
${public_host_line}
}
EOF
